// Regenerates the Drizzle schema (lib/schema.ts, lib/relations.ts) from the tables lib/db.ts creates.
//   npm run db:schema          rewrite the two files
//   npm run db:check           fail when they are out of date (for CI)
// lib/db.ts stays the one place tables, row-level security and migrations are defined. This builds a throwaway local
// database with it, reads the tables back with drizzle-kit, and writes the typed schema. It never touches your own
// database (data/db or DATABASE_URL).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'tf-drizzle-'));
try {
  const env = { ...process.env, TICKETFORGE_DATA: path.join(tmp, 'data'), DATABASE_URL: '', SUPABASE_DB_URL: '' };
  execFileSync(process.execPath, ['--import', 'tsx', '--input-type=module', '-e',
    `const m = await import(${JSON.stringify(path.join(root, 'lib/db.ts'))}); await m.migrate(); await (await m.db()).close(); process.exit(0);`],
  { cwd: root, env, stdio: ['ignore', 'ignore', 'inherit'] });
  const out = path.join(tmp, 'out');
  const cfg = path.join(tmp, 'drizzle.json');
  fs.writeFileSync(cfg, JSON.stringify({ dialect: 'postgresql', driver: 'pglite', dbCredentials: { url: path.join(tmp, 'data', 'db') }, out }));
  execFileSync(path.join(root, 'node_modules/.bin/drizzle-kit'), ['pull', `--config=${cfg}`], { cwd: root, env, stdio: ['ignore', 'ignore', 'inherit'] });

  const banner = '// Generated by `npm run db:schema` from lib/db.ts (do not edit by hand: change the tables in lib/db.ts, then run it again).\n';
  const files = {
    'lib/schema.ts': banner + fs.readFileSync(path.join(out, 'schema.ts'), 'utf8')
      .replace(/mode: 'string'/g, "mode: 'date'") // the database drivers hand back Date objects
      .replace(/\.default\('\)/g, ".default('')") // drizzle-kit prints an empty-string default as default(')
      .replace(/\bunknown\("/g, 'bytea("') // drizzle-kit can't name bytea (uploaded files, screenshots)
      .replace(/^(import \{ pgTable,)/m, 'import { customType, pgTable,')
      .replace(/(import \{ sql \} from "drizzle-orm"\n)/, `$1\n/** bytea: binary data as a Node Buffer. */\nconst bytea = customType<{ data: Buffer; driverData: Buffer }>({ dataType: () => 'bytea' });\n`)
      .replace(/\n{4,}/g, '\n\n').replace(/\t/g, '  '),
    'lib/relations.ts': banner + fs.readFileSync(path.join(out, 'relations.ts'), 'utf8').replace(/\t/g, '  '),
  };
  let stale = 0;
  for (const [file, text] of Object.entries(files)) {
    const dest = path.join(root, file);
    const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : '';
    if (check) { if (cur !== text) { stale++; console.error(`${file} is out of date.`); } }
    else { fs.writeFileSync(dest, text); console.log(`Wrote ${file}${cur === text ? ' (unchanged)' : ''}`); }
  }
  if (check) { if (stale) { console.error('Run `npm run db:schema` and commit the result.'); process.exitCode = 1; } else console.log('Drizzle schema is up to date.'); }
} finally { fs.rmSync(tmp, { recursive: true, force: true }); }
