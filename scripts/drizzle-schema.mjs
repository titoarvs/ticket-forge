// Regenerates the Drizzle schema (one file per table in lib/schema/, plus lib/relations.ts) from
// the tables lib/db.ts creates.
//   npm run db:schema rewrite the files npm run db:check fail when they are out of date (for CI)
// lib/db.ts stays the one place tables, row-level security and migrations are defined. This builds
// a throwaway local database with it, reads the tables back with drizzle-kit, and writes the typed
// schema. It never touches your own database (data/db or DATABASE_URL). Every table gets its own
// file (lib/schema/<table-name>.ts) so a table is easy to find and read; lib/schema/index.ts
// re-exports them all.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'tf-drizzle-'));
const fileOf = (table) => table.replace(/_/g, '-');
try {
  const env = {
    ...process.env,
    TICKETFORGE_DATA: path.join(tmp, 'data'),
    DATABASE_URL: '',
    SUPABASE_DB_URL: '',
  };
  execFileSync(
    process.execPath,
    [
      '--import',
      'tsx',
      '--input-type=module',
      '-e',
      `const m = await import(${JSON.stringify(path.join(root, 'lib/db.ts'))}); await m.migrate(); await (await m.db()).close(); process.exit(0);`,
    ],
    { cwd: root, env, stdio: ['ignore', 'ignore', 'inherit'] },
  );
  const out = path.join(tmp, 'out');
  const cfg = path.join(tmp, 'drizzle.json');
  fs.writeFileSync(
    cfg,
    JSON.stringify({
      dialect: 'postgresql',
      driver: 'pglite',
      dbCredentials: { url: path.join(tmp, 'data', 'db') },
      out,
    }),
  );
  execFileSync(path.join(root, 'node_modules/.bin/drizzle-kit'), ['pull', `--config=${cfg}`], {
    cwd: root,
    env,
    stdio: ['ignore', 'ignore', 'inherit'],
  });

  const banner =
    '// Generated by `npm run db:schema` from lib/db.ts (do not edit by hand: change the table in lib/db.ts, then run it again).\n';
  const raw = fs
    .readFileSync(path.join(out, 'schema.ts'), 'utf8')
    .replace(/mode: 'string'/g, "mode: 'date'") // the database drivers hand back Date objects
    .replace(/\.default\('\)/g, ".default('')") // drizzle-kit prints an empty-string default as default(')
    .replace(/\bunknown\("/g, 'bytea("') // drizzle-kit can't name bytea (uploaded files, screenshots)
    .replace(/\n{4,}/g, '\n\n')
    .replace(/\t/g, '  ');
  const files = {
    'lib/relations.ts':
      banner +
      fs
        .readFileSync(path.join(out, 'relations.ts'), 'utf8')
        .replace(/\t/g, '  ')
        .replace('from "./schema"', 'from "./schema/index"'),
    'lib/schema/bytea.ts': `${banner}import { customType } from "drizzle-orm/pg-core"\n\n/** bytea: binary data as a Node Buffer. */\nexport const bytea = customType<{ data: Buffer; driverData: Buffer }>({ dataType: () => 'bytea' });\n`,
  };

  // One block per table, each with only the imports it uses.
  const pgCore = (raw.match(/import \{([^}]*)\} from "drizzle-orm\/pg-core"/)?.[1] || '')
    .split(',')
    .map((x) => x.trim())
    .filter((x) => x && x !== 'pgTable' && x !== 'customType');
  const tables = raw
    .split(/^(?=export const \w+ = pgTable\()/m)
    .slice(1)
    .map((b) => ({
      id: b.match(/^export const (\w+)/)[1],
      name: b.match(/pgTable\("([^"]+)"/)[1],
      text: b.replace(/\n+$/, '\n'),
    }));
  for (const t of tables) {
    const used = ['pgTable', ...pgCore.filter((n) => new RegExp(`\\b${n}\\(`).test(t.text))];
    const imports = [`import { ${used.join(', ')} } from "drizzle-orm/pg-core"`];
    if (/\bsql`/.test(t.text)) imports.push('import { sql } from "drizzle-orm"');
    if (/\bbytea\(/.test(t.text)) imports.push('import { bytea } from "./bytea"');
    for (const o of tables)
      if (o.id !== t.id && new RegExp(`\\b${o.id}\\.`).test(t.text))
        imports.push(`import { ${o.id} } from "./${fileOf(o.name)}"`);
    files[`lib/schema/${fileOf(t.name)}.ts`] = `${banner}${imports.join('\n')}\n\n${t.text}`;
  }
  files['lib/schema/index.ts'] = `${banner}export * from "./bytea"\n${tables
    .map((t) => fileOf(t.name))
    .sort()
    .map((n) => `export * from "./${n}"`)
    .join('\n')}\n`;

  let stale = 0;
  fs.mkdirSync(path.join(root, 'lib/schema'), { recursive: true });
  for (const f of fs.readdirSync(path.join(root, 'lib/schema'))) {
    // the file of a table that no longer exists
    if (files[`lib/schema/${f}`]) continue;
    if (check) {
      stale++;
      console.error(`lib/schema/${f} is no longer a table.`);
    } else {
      fs.rmSync(path.join(root, 'lib/schema', f));
      console.log(`Removed lib/schema/${f}`);
    }
  }
  for (const [file, text] of Object.entries(files)) {
    const dest = path.join(root, file);
    const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : '';
    if (check) {
      if (cur !== text) {
        stale++;
        console.error(`${file} is out of date.`);
      }
    } else {
      fs.writeFileSync(dest, text);
      console.log(`Wrote ${file}${cur === text ? ' (unchanged)' : ''}`);
    }
  }
  if (check) {
    if (stale) {
      console.error('Run `npm run db:schema` and commit the result.');
      process.exitCode = 1;
    } else console.log('Drizzle schema is up to date.');
  }
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}
